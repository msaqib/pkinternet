#!/usr/bin/env python3
"""
Render WORKED_EXAMPLE.md: every rule applied, in order, to one real suspect.

Nothing is typed by hand. Re-run after any stage changes.

  python write_worked_example.py [--target 58.27.233.225]
"""
import io, json, os, argparse, ipaddress, collections, statistics as st

H = os.path.dirname(os.path.abspath(__file__))
def P(*p): return os.path.join(H, "..", *p)

ap = argparse.ArgumentParser()
ap.add_argument("--target", default="58.27.233.225")
A = ap.parse_args()
T = A.target
U = str(ipaddress.ip_network(T + "/24", strict=False))

R = json.load(io.open(os.path.join(H, "rules_local.json"), encoding="utf-8"))
D = json.load(io.open(os.path.join(H, "trombone_local.json"), encoding="utf-8"))
ann = json.load(io.open(P("3_routes", "selected_annotated.json"), encoding="utf-8"))
own = json.load(io.open(P("1_universe", "block_to_asn.json"), encoding="utf-8"))
hold = json.load(io.open(P("1_universe", "asn_holder.json"), encoding="utf-8"))
base = json.load(io.open(P("3_routes", "rtt_baseline_sample.json"), encoding="utf-8"))

rtt = {}
for fn, how in (("rtt_foreign.json", "direct echo"), ("rtt_foreign_ttl.json", "in-path"),
                ("rtt_inpath.json", "in-path")):
    fp = P("3_routes", fn)
    if os.path.exists(fp):
        for ip, v in json.load(io.open(fp, encoding="utf-8")).items():
            if v.get("n"):
                rtt[ip] = dict(v, how=how)

trace = next(r for r in ann if r["target"] == T)
verdict = next(r for r in D["rows"] if r["target"] == T)
asn = own.get(U)
FENCE = R["R4prime"]["fence_ms"]
FALS = R["R2"]["falsified_detail"]
CH = [c["ip"] for c in R["R1"]["chain"]]

# liveness provenance
checked, live, byscan = 0, [], collections.Counter()
pre = U.rsplit(".", 1)[0] + "."
for fn, tag in (("local_scan.jsonl", "earlier small-ISP scan"),
                ("pk_scan.jsonl", "main sweep, from TES"),
                ("topup_scan.jsonl", "top-up, from Mobilink")):
    fp = P("2_liveness", fn)
    if not os.path.exists(fp):
        continue
    for l in io.open(fp, encoding="utf-8"):
        try: d = json.loads(l)
        except Exception: continue
        if d["t"].startswith(pre):
            checked += 1; byscan[tag] += 1
            if d["m"]: live.append((d["t"], tag))

def hopline(i, h):
    if not h:
        return f"| {i} | `*` | | | | silent |"
    m = rtt.get(h["ip"])
    r = f"{m['min']} ms" if m else (f"{h['rtt']:.0f} ms*" if isinstance(h.get("rtt"), (int, float)) else "")
    note = ""
    if h["ip"] in CH: note = "access chain (R1)"
    elif h["ip"] in FALS: note = "**squatted** (R2)"
    elif h["cc"] in ("PRIV", "CGN"): note = "private"
    elif h["cc"] != "PK": note = "**FOREIGN**"
    return (f"| {i} | `{h['ip']}` | {r} | {h['cc']} | "
            f"{(h.get('holder') or '')[:26]} | {note} |")

path_tbl = "\n".join(hopline(i, h) for i, h in enumerate(trace["path"], 1))
exit_ip = verdict["exit_ip"]
exit_hop = next((h for h in trace["path"] if h and h["ip"] == exit_ip), None)
exit_m = rtt.get(exit_ip, {})
fl = R["country_floors"].get(verdict["exit_cc"], {})

dom = sorted(v["min"] for t, v in base.items()
             if next((x["status"] for x in D["rows"] if x["target"] == t), "") == "local")
q = st.quantiles(dom, n=4)

sq = [h for h in trace["path"] if h and h["ip"] in FALS]
sq_tbl = "\n".join(
    f"| `{h['ip']}` | {FALS[h['ip']]['cc']} | {FALS[h['ip']]['rtt']:.0f} ms | "
    f"{FALS[h['ip']]['floor']:.0f} ms | {FALS[h['ip']]['holder'][:30]} |" for h in sq) or \
    "| none in this trace | | | | |"

md = f"""# One suspect, every rule, in order

**Target `{T}`, block `{U}`, announced by AS{asn} {hold.get(asn,'')[:40]}.**

Generated by `write_worked_example.py`. Every figure is read from the pipeline's own
output, so this page cannot drift from the code.

This follows a single Pakistani address from the moment it entered the study to the
moment it was called a detour, applying R0 to R6 in the order the rules require.

---

## How this address entered the study at all

**Universe.** `{U}` is one of 22,556 /24 blocks in the union of Pakistan's registered and
announced space.

**Liveness.** The sampler drew 8 random addresses at a time from the block's 256:

| pass | addresses checked |
|---|--:|
""" + "\n".join(f"| {k} | {v} |" for k, v in byscan.items()) + f"""
| **total** | **{checked} of 256** |

**{len(live)} answered.** `{T}` was found by the **{dict(live).get(T,'?')}**.

That matters for what follows: the main sweep spent its full 64-check budget on this
block and found 3 hosts; a second vantage found the rest in half the effort. "Alive" is
vantage-relative, and this block is a small instance of the ~9% cross-vantage
disagreement recorded in `../SWEEP_FINDINGS.md` 5B.

**Selection.** The trace reached its target and answered {trace['answered']} of
{trace['hops_total']} TTL slots, clearing the gate of `reached AND >= 5 answered`.

---

## R0 — is the measurement usable?

The sweep's own RTT for this trace is **not** usable. Across the selection, 22% of
adjacent hop pairs show RTT falling more than 20 ms deeper into the path, which distance
cannot do, and one fixed router spans 4 to 853 ms.

So every latency figure below comes from a **re-measurement**: 20 to 30 packets per
address at 6 to 8 threads, in-path, keeping the minimum. Dispersion on those bursts is
1 to 2 ms. Values marked `*` are sweep figures with no clean re-measurement available and
must not be used for a verdict.

**R0 passes on the re-measured data. It failed on the sweep data.**

## R1 — subtract this vantage's access path

The first three public hops are the same in ~99% of all traces from this vantage:

""" + "\n".join(f"* `{c['ip']}` ({c['pct']}% of traces)" for c in R["R1"]["chain"]) + f"""

**B_access = {R['R1']['B_access_ms']:.0f} ms**, paid before anything is measured. Nothing in that
chain can be a detour, so it is subtracted first.

## The path itself

| hop | address | clean RTT | cc | holder | rule |
|--:|---|--:|---|---|---|
{path_tbl}

## R2 — strip addresses that are not where they claim

A foreign registry country is not evidence. 4.4% of Pakistan's routed space is
legitimately foreign-registered, and operators number backbones out of space they do not
announce. R2 asks a physical question instead: could a packet reach the claimed location
and return this fast?

Falsified hops in this trace:

| address | claims | clean RTT | physical floor | holder |
|---|---|--:|--:|---|
{sq_tbl}

Across the whole study R2 falsified **{R['R2']['falsified']} addresses**, including seven US
Department of Defense addresses answering in about 3 ms. Without this step, those hops
would be counted as departures and would fabricate thousands of detours.

## R3 — can this vantage see paths at all?

Yes, under ICMP: 3 of 43,765 traces contained no public router. This trace contains
{sum(1 for h in trace['path'] if h and h['cc'] not in ('PRIV','CGN'))} public hops.

## R4′ — is what remains actually foreign, or just not where it claims?

R2 kills a registry claim. It does not prove an address is in Pakistan. So each surviving
suspect is checked against **this vantage's own domestic distribution**, built from
{R['R4prime']['reference_n']} destinations whose paths are entirely domestic:

| | ms |
|---|--:|
| domestic median | {st.median(dom):.0f} |
| p25 / p75 | {q[0]:.0f} / {q[2]:.0f} |
| **fence (p75 + 3 × IQR)** | **{FENCE:.0f}** |

**R4' is only consulted for addresses R2 falsified.** If a registry claim survives R2,
the address is where it says it is, and its latency adds nothing.

The suspect hop `{exit_ip}` measures **{exit_m.get('min','?')} ms**
({exit_m.get('how','?')}, {exit_m.get('n','?')} packets, dispersion {exit_m.get('spread','?')} ms).
Its claimed country {verdict['exit_cc']} has a straight-line floor of
**{fl.get('floor_ms','?')} ms** from the nearest Pakistani origin. {exit_m.get('min','?')} ms
clears that floor, so **R2 does not falsify the claim** and R4' does not run on this hop.
The address is in {verdict['exit_cc']}, and the hop is a departure.

**A caution this example makes concrete.** {exit_m.get('min','?')} ms also sits *below* this
vantage's {FENCE:.0f} ms domestic fence. That is not a contradiction: western China is
roughly 1,400 km from Pakistan, so a genuine Chinese hop can cost less than a slow
domestic path. **Latency alone could never have found this detour** — only topology did.
The same is true of the Gulf, and it is why R4' is a second net for what topology misses
rather than a test that could replace it.

## R5 — the verdict

```
1. access chain subtracted           R1
2. squatted space removed            R2  ({len(sq)} hop(s) in this trace)
3. survivors tested against the fence R4'
4. what is left is a departure
```

**`{T}` is a trombone.** A Pakistani source reached a Pakistani destination
(AS{asn} {hold.get(asn,'')[:30]}) by way of `{exit_ip}` in **{verdict['exit_cc']}**
({verdict['exit_holder'][:34]}).

## R6 — does the verdict predict anything it was not given?

The topological test never saw a latency figure. If it is detecting something real, its
verdicts should still separate on latency:

| | n | median clean RTT |
|---|--:|--:|
| called domestic | {len(dom)} | **{st.median(dom):.0f} ms** |
| called tromboning | {len([1 for t,v in base.items() if next((x['status'] for x in D['rows'] if x['target']==t),'')=='trombone'])} | **{st.median([v['min'] for t,v in base.items() if next((x['status'] for x in D['rows'] if x['target']==t),'')=='trombone']):.0f} ms** |

The separation is real and was not used to produce the verdict.

---

## What this one example does and does not show

**Shows.** Every rule firing in order on real data, with each threshold derived from
measurement rather than chosen, and two independent lines of evidence agreeing.

**Does not show.** That this is representative. All {len([r for r in D['rows'] if r['block']==U and r['status']=='trombone'])}
selected hosts in `{U}` trombone through the same exit, because **tromboning is a property
of the destination prefix, not of individual hosts**: 146 of 157 tromboning blocks are
all-or-nothing. So this block is one observation, not seven.

**Does not show** anything about detours we cannot see. The result is a floor: a detour
through routers that stay silent, or inside an MPLS tunnel, is recorded as domestic.

**Not confirmed by any operator.**
"""
io.open(os.path.join(H, "WORKED_EXAMPLE.md"), "w", encoding="utf-8").write(md)
print(f"wrote WORKED_EXAMPLE.md ({len(md):,} chars) for {T}")
