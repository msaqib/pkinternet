import io, json, os, collections, ipaddress, statistics as st

H = os.path.dirname(os.path.abspath(__file__))
def P(*p): return os.path.join(H, "..", *p)

R = json.load(io.open(os.path.join(H, "rules_local.json"), encoding="utf-8"))
D = json.load(io.open(os.path.join(H, "trombone_local.json"), encoding="utf-8"))
ann = json.load(io.open(P("3_routes", "selected_annotated.json"), encoding="utf-8"))
own = json.load(io.open(P("1_universe", "block_to_asn.json"), encoding="utf-8"))
hold = json.load(io.open(P("1_universe", "asn_holder.json"), encoding="utf-8"))
isp = json.load(io.open(P("6_analysis", "isp_summary.json"), encoding="utf-8"))
C = R["constants"]
F = R["country_floors"]

TOT = {k: sum(r[k] for r in isp) for k in ("blocks", "addrs", "checks", "live", "liveblk", "traces", "reached", "sel", "selblk")}

rows = D["rows"]
tb = [r for r in rows if r["status"] == "trombone"]
blk = collections.Counter(r["block"] for r in tb)
allblk = collections.Counter(r["block"] for r in rows)
asn = collections.Counter(r["asn"] for r in tb)
allt = sum(1 for b, n in blk.items() if n == allblk[b])
same = sum(1 for b in blk if len({r["exit_ip"] for r in tb if r["block"] == b}) == 1)

per = collections.defaultdict(lambda: [0, 0])
for r in rows:
    if r["asn"]:
        per[r["asn"]][0] += 1
        if r["status"] == "trombone":
            per[r["asn"]][1] += 1
ranked = sorted(((a, n, t) for a, (n, t) in per.items() if n >= 100), key=lambda z: -z[2]/z[1])

# worked example: the block traced end to end
EX = "58.27.233.0/24"
ex_rows = [r for r in rows if r["block"] == EX]
ex_ann = {r["target"]: r for r in ann if r["block"] == EX}

cc_tbl = "\n".join(f"| {c} | {n:,} | {F.get(c,{}).get('floor_ms','?')} | {F.get(c,{}).get('hub','?')} |"
                   for c, n in D["by_country"][:8])
