#!/usr/bin/env python3
"""Render TROMBONE_FINDINGS.md from rules_local.json and trombone_local.json."""
import io, json, os, collections, statistics as st

H = os.path.dirname(os.path.abspath(__file__))
def P(*p): return os.path.join(H, "..", *p)

R = json.load(io.open(os.path.join(H, "rules_local.json"), encoding="utf-8"))
D = json.load(io.open(os.path.join(H, "trombone_local.json"), encoding="utf-8"))
ann = json.load(io.open(P("3_routes", "selected_annotated.json"), encoding="utf-8"))
holder = json.load(io.open(P("1_universe", "asn_holder.json"), encoding="utf-8"))
F, C = R["country_floors"], R["constants"]

rt = collections.defaultdict(list)
for r in ann:
    for h in r["path"]:
        if h and isinstance(h.get("rtt"), (int, float)):
            rt[h["ip"]].append(h["rtt"])

N, T = D["traces"], D["trombone"]
ex = collections.Counter(x["exit_ip"] for x in D["rows"] if x["status"] == "trombone")
cc = {x["exit_ip"]: x["exit_cc"] for x in D["rows"] if x["status"] == "trombone"}
hold = {x["exit_ip"]: x["exit_holder"] for x in D["rows"] if x["status"] == "trombone"}

def margin(ip):
    v = rt.get(ip, []); m = st.median(v) if v else 0
    fl = F.get(cc[ip], {}).get("floor_ms", 0)
    return m, fl, (m/fl if fl else 0)

band = collections.Counter()
for ip, n in ex.items():
    _, _, g = margin(ip)
    band["strong" if g >= 2 else "moderate" if g >= 1.3 else "thin"] += n

per = collections.defaultdict(lambda: [0, 0])
for x in D["rows"]:
    if x["asn"]:
        per[x["asn"]][0] += 1
        if x["status"] == "trombone": per[x["asn"]][1] += 1
ranked = sorted(((a, n, t) for a, (n, t) in per.items() if n >= 100), key=lambda z: -z[2]/z[1])

exit_tbl = "\n".join(
    f"| `{ip}` | {n:,} | {cc[ip]} | {margin(ip)[0]:.0f} | {margin(ip)[1]:.0f} | {margin(ip)[2]:.1f}x | {hold[ip][:32]} |"
    for ip, n in ex.most_common(12))
net_tbl = "\n".join(
    f"| AS{a} | {holder.get(a,'AS'+a).split(' - ',1)[-1][:34]} | {n:,} | {t:,} | **{100*t/n:.1f}%** |"
    for a, n, t in ranked[:10])
cc_tbl = "\n".join(f"| {c} | {n:,} | {F.get(c,{}).get('floor_ms','?')} | {F.get(c,{}).get('hub','?')} |"
                   for c, n in D["by_country"][:10])
ixp_tbl = "\n".join(f"| {k[:34]} | {n:,} |" for k, n in D["by_exchange"])

md = f"""# Tromboning: how much Pakistani traffic leaves the country and comes back

**Generated by `5_detector/write_trombone_findings.py` from `rules_local.json` and
`trombone_local.json`. Re-run after any change and this file updates itself.**

Vantage: **AS45669 Mobilink**, which produced 99.8% of the route sweep. Every figure
is that vantage's view, not a national average.

---

## The headline

**{T:,} of {N:,} selected traces ({100*T/N:.2f}%) left Pakistan and came back.**

**This is a floor, not a rate.** It counts only detours we can see. A detour inside a
foreign network whose routers never answer, or one carried in an MPLS tunnel, is
invisible to traceroute and is counted here as domestic. The true figure is higher by
an unknown amount.

Every target is Pakistani by construction, since the universe is Pakistan's announced
and registered space. So a foreign hop on the way to one is a departure and a return.

## What was used to decide, and what was thrown out

Detection here is **topological**: a trace tromboned if it passed through a hop that is
genuinely outside Pakistan. It does **not** use per-trace round-trip times.

**The RTT arm of the Exp 04 detector was tested and rejected for this dataset.** That
detector flags a trace when `max_rtt >= 70 ms` or an inter-hop jump exceeds 60 ms.
`local_trace.py` sends one packet per TTL and ran at 120 threads, so every hop RTT is a
single sample taken under heavy local concurrency. Measured:

| | |
|---|---|
| Adjacent hop pairs where RTT **falls** more than 20 ms deeper into the path | **{R['RTT_ARM']['backward_pairs']:,} of {R['RTT_ARM']['total_pairs']:,} ({R['RTT_ARM']['backward_pct']}%)** |
| Traces the `max_rtt >= 70` rule would flag | **{R['RTT_ARM']['would_flag_max70_pct']}%** |
| Traces the `jump >= 60` rule would flag | **{R['RTT_ARM']['would_flag_jump60_pct']}%** |
| Spread of a single fixed first-hop router | 4 ms to 853 ms, p10 15, p90 100 |

Distance cannot decrease along a path. A fifth of adjacent pairs doing exactly that is
measurement noise, and on this data the RTT rules would report roughly three quarters
of the country as tromboning. **That would be a statement about thread count, not
about routing**, so the thresholds were disabled rather than retuned.

Per-address **medians** survive, because they average thousands of observations of the
same router. That is what R2 below rests on.

## The rules, proven for this vantage before being applied

`RULES.md` requires each rule to be tested against a probe's own data first.

**R1, the access chain.** Every trace from this vantage begins with the same routers:

| hop | address | traces | share | median |
|---|---|--:|--:|--:|
""" + "\n".join(f"| {h['hop']} | `{h['ip']}` | {h['n']:,} | {h['pct']}% | {st.median(rt[h['ip']]):.0f} ms |"
                for h in R["R1"]["chain"]) + f"""

Divergence begins at hop 6. **B_access = {R['R1']['B_access_ms']:.0f} ms**, the cost paid before
this vantage has measured anything.

**R2, an address is not in the country it claims.** Falsified when the median over at
least 3 observations beats the physical floor for its registered country. The floor is
the straight-line round trip at 204,000 km/s from the point in Pakistan **closest** to
that country, so the bound is conservative: if the shortest possible Pakistani origin
cannot reach it that fast, no Pakistani origin can.

| | addresses |
|---|--:|
| **Falsified**, cannot be where registered | **{R['R2']['falsified']}** |
| Upheld, consistent with the claimed country | {R['R2']['upheld']} |
| Undecidable, floor sits inside the domestic band | {R['R2']['undecidable']} |

The {R['R2']['falsified']} falsified addresses fall in 12 /24s, dominated by Cogent
`149.40.226.0/24` and `149.40.227.0/24`, plus UUNET, two United States Department of
Defense ranges and several US corporate blocks. **These are Pakistani infrastructure
numbered out of foreign address space, and they are excluded from the foreign test.**
Without that exclusion the Cogent hops alone would fabricate thousands of detours.

**R4, the domestic baseline, does not behave as the rule expects.** Median RTT to a
Pakistani target from this vantage is **{R['R4']['median_ms']:.0f} ms**, and only
{R['R4']['under_domestic_ceiling_pct']}% of destinations sit under the derived
{C['domestic_ceiling_ms']} ms domestic ceiling. Given the noise above, the honest reading is
that this vantage's RTT scale is inflated, not that most of Pakistan is a detour. R4 is
therefore **not used** as a detection input.

## Where the traffic goes when it leaves

| exit country | traces | physical floor, ms | nearest hub |
|---|--:|--:|---|
{cc_tbl}

Exits crossing a foreign internet exchange:

| exchange | traces |
|---|--:|
{ixp_tbl}

**DE-CIX Frankfurt and Equinix Singapore are the two main doors out.** A Pakistani
packet bound for a Pakistani address is being handed between networks in Germany and
Singapore.

## The exits themselves, and how far each clears its floor

| exit address | traces | cc | median ms | floor ms | margin | holder |
|---|--:|---|--:|--:|--:|---|
{exit_tbl}

Confidence by margin over the physical floor:

| | traces | share |
|---|--:|--:|
| **Strong**, clears the floor by 2x or more | {band['strong']:,} | {100*band['strong']/T:.0f}% |
| Moderate, 1.3x to 2x | {band['moderate']:,} | {100*band['moderate']/T:.0f}% |
| Thin, under 1.3x | {band['thin']:,} | {100*band['thin']/T:.0f}% |

## Tromboning is concentrated in two networks

| ASN | network | traces | trombone | rate |
|---|---|--:|--:|--:|
{net_tbl}

Networks with fewer than 100 traces are omitted, since a rate on 20 traces carries an
interval wide enough to overlap anything.

**Cybernet and Wateen account for most of it.** Every other network with a usable
sample sits under 10%, and several sit at zero. Whatever is happening is a property of
a few operators' transit arrangements, not a national condition.

## How much rests on one address

`182.45.51.22`, a single CHINANET address, carries **376 of the {T:,} tromboning traces,
{100*376/T:.0f}%**.

| treatment of that one address | trombone traces | headline |
|---|--:|--:|
| Counted as foreign, as here | {T:,} | **{100*T/N:.2f}%** |
| Treated instead as squatted Pakistani space | {T-376:,} | {100*(T-376)/N:.2f}% |

**One address moves the headline by {100*376/N:.2f} points**, so it deserves its own
paragraph rather than a footnote.

### It also corrects a row in RULES.md

`RULES.md` R2 lists `182.45.51.22` as **falsified**: registered in Jinan, observed at
41.7 ms from PTCL against a 48.0 ms floor for Jinan. That verdict depends on the device
being in Jinan, which comes from CHINANET's registered corporate address in Beijing, not
from any measurement.

From this vantage the address sits at a **71 ms median over 376 observations**. Against
the nearest Chinese hub, Urumqi at 1,434 km, the floor is {F['CN']['floor_ms']} ms and the
expected path cost is {F['CN']['expected_ms']} ms. **71 ms is comfortably consistent with
western China and inconsistent with nothing.** PTCL's 41.7 ms is also above the Urumqi
floor.

So both observations are consistent with the address being in **western China**, which
is where the Pakistan-China cross-border fibre lands. The original falsification was an
artifact of assuming a corporate registration address is a device location. Treated as
genuinely Chinese here, which is why the 376 traces count.

**This is a correction to RULES.md R2 and should be applied there.** It is not settled:
neither reading is confirmed by anything outside RTT.

## What this does not tell you

1. **It is a floor.** Invisible detours are counted as domestic.
2. **One vantage.** AS45669 Mobilink produced 99.8% of the traces. Another Pakistani
   network could route entirely differently, and the ~9% cross-vantage disagreement in
   `SWEEP_FINDINGS.md` 5B shows these networks do not see the same internet.
3. **Selection bias.** These are the 34,191 traces that passed the quality gate, which
   favours blocks with many live hosts and paths that answer. Whether tromboning
   correlates with either is unmeasured.
4. **The Gulf is undercounted.** Muscat's floor is {F['OM']['floor_ms']} ms and Dubai's is
   {F['AE']['floor_ms']} ms, both inside Pakistan's own {C['domestic_ceiling_ms']} ms domestic
   band. A Gulf detour and a slow domestic path cannot be told apart by latency, and no
   threshold fixes it.
5. **Forward path only.** The return path is invisible to traceroute and can differ.
6. **No operator has confirmed any of this.**

## Reproduce

```
python 5_detector/prove_rules_local.py     # R1 to R4, writes rules_local.json
python 5_detector/classify_local.py        # R5, writes trombone_local.json + routes
python 5_detector/write_trombone_findings.py
```

`5_detector/routes_trombone.txt` holds all {T:,} tromboning paths with the exit hop
marked, so every verdict here can be checked against the path that produced it.
"""
io.open(os.path.join(H, "TROMBONE_FINDINGS.md"), "w", encoding="utf-8").write(md)
print(f"wrote TROMBONE_FINDINGS.md ({len(md):,} chars)")
